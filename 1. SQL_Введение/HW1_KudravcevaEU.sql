-- необходимо посчитать общий объём зарплатного бюджета, заложенного в открытые вакансии направления, то правильно было бы 
-- написать отдельный подзапрос, который посчитает каждую зарплату только по 1 разу. Однако, для сравнения уровней зарплат 
-- между направлениями сумма по всем зарплатам не подходит, так как она напрямую зависит от количества вакансий (чем больше 
-- вакансий в направлении, тем больше сумма). Поэтому я заменила её на среднюю зарплату (AVG(salary_from)), которая 
-- показывает среднюю зарплату на одну вакансию. При этом подсчет также проводится через подзапрос, чтобы избежать размножения.
--
-- 5. Также для улучшения добавила count(r.response_id)::DECIMAL - чтобы получить дробный ответ, округлила ответ до 1 знака,
-- знаменатель защитила NULLIF

-- Исправленный запрос:
 SELECT v.professional_role,
 count(DISTINCT v.vacancy_id) AS vacancies,
 (SELECT ROUND(AVG(v2.salary_from), 0)
 FROM vacancies v2 
 WHERE v2.professional_role = v.professional_role
 AND v2.closed_at IS NULL) AS average_salary,
 ROUND((count(r.response_id)::DECIMAL / nullif(count(DISTINCT v.vacancy_id), 0)), 1) AS responses_per_vacancy
 FROM vacancies v
 LEFT JOIN responses r ON v.vacancy_id = r.vacancy_id
 WHERE v.closed_at IS NULL
 GROUP BY 1;

