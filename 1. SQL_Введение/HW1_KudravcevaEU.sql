-- ЗАДАНИЕ Д1
-- Запрос: помесячная динамика откликов и конверсия
-- (месяц как дата, условный агрегат, nullif в знаменателе)
SELECT date_trunc('month', created_at)::date AS month,
count(response_id) AS responses,
count(response_id) FILTER (WHERE status = 'invited') AS invited,
round(100.0 * count(response_id) FILTER (WHERE status = 'invited')
/ nullif(count(response_id), 0), 1) AS conversion_pct
FROM responses 
GROUP BY date_trunc('month', created_at)
ORDER BY month;

--Последние даты отклика по каждому месяцу 
SELECT date_trunc('month', created_at)::date AS month,
MAX(created_at) AS last_response
FROM responses 
GROUP BY date_trunc('month', created_at)
ORDER BY month;
